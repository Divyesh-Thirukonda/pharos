def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def public_error(exc: Exception) -> str:
    """Avoid reflecting provider URLs, credentials, response bodies, or tokens."""
    if isinstance(exc, httpx.HTTPStatusError):
        return f"The source returned HTTP {exc.response.status_code}."
    if isinstance(exc, (httpx.TimeoutException, asyncio.TimeoutError)):
        return "The source timed out."
    return "The source could not be reached or returned an unsupported response."


