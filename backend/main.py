def normalize_street(value: Any) -> str:
    name = re.sub(r"\s+", " ", str(value or "").upper().replace(".", " ")).strip()
    name = re.sub(r"\b(\d+)(ST|ND|RD|TH)\b", r"\1", name)
    replacements = {"STREET": "ST", "AVENUE": "AVE", "BOULEVARD": "BLVD", "ROAD": "RD", "PLACE": "PL", "PARKWAY": "PKWY", "EAST": "E", "WEST": "W", "NORTH": "N", "SOUTH": "S"}
    return " ".join(replacements.get(word, word) for word in name.split())


def valid_coordinate(lat: Any, lon: Any) -> bool:
    try:
        return 40.68 <= float(lat) <= 40.89 and -74.04 <= float(lon) <= -73.90
    except (ValueError, TypeError):
        return False


def count_value(row: dict, field: str) -> int:
    try:
        return max(0, int(float(row.get(field, 0) or 0)))
    except (ValueError, TypeError, OverflowError):
        return 0


def crash_hour(value: Any) -> int | None:
    # NYC's crash_time is a reported local wall-clock time, not an ISO instant.
    match = re.fullmatch(r"\s*(\d{1,2}):([0-5]\d)(?::[0-5]\d)?\s*", str(value or ""))
    return int(match[1]) if match and int(match[1]) < 24 else None


def hourly_crashes(rows: list[dict]) -> dict:
    counts, missing = [0] * 24, 0
    for row in rows:
        hour = crash_hour(row.get("crash_time"))
        if hour is None:
            missing += 1
        else:
            counts[hour] += 1
    return {"hourlyCounts": counts, "hourlyKnownCrashes": sum(counts), "hourlyMissingCrashes": missing}


def aggregate_crashes(rows: list[dict]) -> dict:
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    seen: set[str] = set()
    excluded = 0
    manhattan_rows = []
    for row in rows:
        collision_id = str(row.get("collision_id") or "")
        if collision_id and collision_id in seen:
            continue
        if collision_id:
            seen.add(collision_id)
        if row.get("borough", "MANHATTAN").upper() == "MANHATTAN":
            manhattan_rows.append(row)
        # Socrata's internal names are inverted: off_street_name is displayed as
        # CROSS STREET NAME; cross_street_name is the off-street street address.
        # Verified against /api/views/h9gi-nx95.json, not inferred from field names.
        a, b = normalize_street(row.get("on_street_name")), normalize_street(row.get("off_street_name"))
        if row.get("borough", "MANHATTAN").upper() != "MANHATTAN" or not a or not b or a == b or not valid_coordinate(row.get("latitude"), row.get("longitude")):
            excluded += 1
            continue
        groups[tuple(sorted((a, b)))].append(row)
    results = []
    for pair, items in groups.items():
        factors = Counter()
        for row in items:
            # Count each reported factor once per collision, across up to five vehicles.
            reported = {str(row.get(f"contributing_factor_vehicle_{i}") or "").strip() for i in range(1, 6)}
            factors.update(value for value in reported if value and value.lower() not in {"unspecified", "unknown", "other vehicular"})
        injuries = sum(count_value(r, "number_of_persons_injured") for r in items)
        fatalities = sum(count_value(r, "number_of_persons_killed") for r in items)
        item = {
            "id": "nyc-" + hashlib.sha256("|".join(pair).encode()).hexdigest()[:12],
            "name": " & ".join(pair), "streets": list(pair),
            "lat": statistics.median(float(r["latitude"]) for r in items),
            "lon": statistics.median(float(r["longitude"]) for r in items),
            "crashes": len(items), "injuryCrashes": sum(count_value(r, "number_of_persons_injured") > 0 for r in items), "injuries": injuries, "fatalities": fatalities,
            "pedestrianInjuries": sum(count_value(r, "number_of_pedestrians_injured") for r in items),
            "cyclistInjuries": sum(count_value(r, "number_of_cyclist_injured") for r in items),
            "factors": [{"name": label, "count": count} for label, count in factors.most_common(5)],
            "cameras": [], "locationAccuracy": "approximate", "source": "NYC motor vehicle collisions",
            "sourceUrl": CRASH_PAGE,
            **hourly_crashes(items),
        }
        results.append(item)
    results.sort(key=lambda item: (-item["injuryCrashes"], -item["crashes"], item["name"]))
    peak = max(1, max((item["injuryCrashes"] for item in results), default=0))
    for item in results:
        item["riskScore"] = round(100 * item["injuryCrashes"] / peak)
    focus_intersections = [{**item, "rankByInjuryCrashes": index + 1} for index, item in enumerate(results)
                           if "W 23 ST" in item["streets"] and ({"6 AVE", "AVE OF THE AMERICAS"} & set(item["streets"]))]
    return {"intersections": results[:100], "totalRows": len(rows), "excludedRows": excluded, "groupCount": len(results),
            "focusIntersections": focus_intersections,
            **hourly_crashes(manhattan_rows), "hourlyTimeZone": "America/New_York", "hourlyCountScope": "all_manhattan_records",
            "hourlyMethodology": "Reported crash counts by local crash_time hour, across all deduplicated Manhattan source records in the period, including records excluded from intersection mapping. Missing or invalid times are excluded from the 24 bins and counted separately; zero means no known-time source records in that bin, not proof of no events."}


async def fetch_crashes() -> dict:
    headers = {"User-Agent": USER_AGENT}
    if os.getenv("SOCRATA_APP_TOKEN"):
        headers["X-App-Token"] = os.environ["SOCRATA_APP_TOKEN"]
    async with httpx.AsyncClient(timeout=45, headers=headers) as client:
        response = await client.get(CRASH_URL, params={"$select": "max(crash_date) as latest", "$where": "borough = 'MANHATTAN'"})
        response.raise_for_status()
        latest = date.fromisoformat(response.json()[0]["latest"][:10])
        try:
            start = latest.replace(year=latest.year - 1) + timedelta(days=1)
        except ValueError:
            start = latest.replace(year=latest.year - 1, day=28) + timedelta(days=1)
        fields = ["collision_id", "crash_date", "crash_time", "borough", "latitude", "longitude", "on_street_name", "off_street_name", "number_of_persons_injured", "number_of_persons_killed", "number_of_pedestrians_injured", "number_of_cyclist_injured", *[f"contributing_factor_vehicle_{i}" for i in range(1, 6)]]
        where = f"borough = 'MANHATTAN' AND crash_date >= '{start.isoformat()}T00:00:00' AND crash_date < '{(latest + timedelta(days=1)).isoformat()}T00:00:00'"
        rows = []
        for offset in range(0, 200000, 10000):
            response = await client.get(CRASH_URL, params={"$select": ",".join(fields), "$where": where, "$order": "collision_id ASC", "$limit": 10000, "$offset": offset})
            response.raise_for_status()
            page = response.json()
            if not isinstance(page, list):
                raise ValueError("Invalid Socrata response")
            rows.extend(page)
            if len(page) < 10000:
                break
        else:
            raise ValueError("Source pagination exceeded safety bound")
    payload = aggregate_crashes(rows)
    payload.update(periodStart=start.isoformat(), periodEnd=latest.isoformat())
    return payload


async def fetch_cameras() -> list[dict]:
    async with httpx.AsyncClient(timeout=20, headers={"User-Agent": USER_AGENT}) as client:
        response = await client.get(CAMERA_URL)
        response.raise_for_status()
        rows = response.json()
    if not isinstance(rows, list):
        raise ValueError("Invalid camera directory")
    cameras = []
    for row in rows:
        if str(row.get("area", "")).upper() != "MANHATTAN" or not valid_coordinate(row.get("latitude"), row.get("longitude")):
            continue
        camera_id = str(row.get("id", ""))
        if not re.fullmatch(r"[A-Za-z0-9-]+", camera_id):
            continue
        image_url = row.get("imageUrl")
        if not isinstance(image_url, str) or not image_url.startswith("https://webcams.nyctmc.org/"):
            image_url = None
        cameras.append({"id": camera_id, "name": row.get("name", "NYC DOT camera"), "lat": float(row["latitude"]), "lon": float(row["longitude"]), "imageUrl": image_url,
                        "status": "online" if str(row.get("isOnline", "")).lower() == "true" else "offline", "source": "latest_image", "officialUrl": f"{CAMERA_PAGE}?cameras={camera_id}", "capturedAt": None, "officialViewerRefreshSeconds": 2})
    return cameras


def distance_meters(a_lat: float, a_lon: float, b_lat: float, b_lon: float) -> int:
    a1, a2 = math.radians(a_lat), math.radians(b_lat)
    dlat, dlon = a2 - a1, math.radians(b_lon - a_lon)
    hav = math.sin(dlat / 2) ** 2 + math.cos(a1) * math.cos(a2) * math.sin(dlon / 2) ** 2
    return round(6371000 * 2 * math.atan2(math.sqrt(hav), math.sqrt(max(0, 1 - hav))))


