def record_service_result(name: str, success: bool, detail: str, model: str | None = None) -> None:
    previous = service_events.get(name, {})
    event = {"lastCheckedAt": utc_now(), "success": success, "detail": detail,
             "lastSuccessAt": utc_now() if success else previous.get("lastSuccessAt"), "_checkedEpoch": time.time()}
    if model or previous.get("model"):
        event["model"] = model or previous["model"]
    service_events[name] = event


def operation_status(name: str, configured: bool) -> dict:
    event = service_events.get(name, {})
    if not configured:
        status, detail = "unavailable", "Server-side connection settings are not configured."
    elif not event:
        status, detail = "unverified", "Configured, but no successful operation has been verified in this running process."
    elif not event["success"]:
        status, detail = "unavailable", event["detail"]
    elif time.time() - event["_checkedEpoch"] > 900:
        status, detail = "stale", "The last operation succeeded more than 15 minutes ago; current connectivity has not been probed."
    else:
        status, detail = "connected", event["detail"]
    return {"configured": configured, "status": status, "detail": detail, "checkType": "runtime_operation",
            "lastCheckedAt": event.get("lastCheckedAt"), "lastSuccessAt": event.get("lastSuccessAt"),
            **({"model": event["model"]} if event.get("model") else {})}


async def gpu_service_status() -> dict:
    from .vision import gpu_headers, service_url, settings_status
    global _gpu_health, _gpu_health_at, _gpu_health_key
    configured = settings_status()
    key = (os.getenv("COSMOS3_REASON_URL"), os.getenv("YOLO_URL"), bool(os.getenv("GPU_BEARER_TOKEN")))
    async with _gpu_health_lock:
        if key != _gpu_health_key or time.monotonic() - _gpu_health_at > 30:
            async def probe(name: str, env: str, path: str):
                enabled = configured[name + "Configured"]
                result = {"configured": enabled, "status": "unavailable", "lastCheckedAt": None,
                          "lastSuccessAt": _gpu_health.get(name, {}).get("lastSuccessAt"),
                          "checkType": "authenticated_models" if name == "cosmos" else "authenticated_health",
                          "detail": "Server-side GPU connection settings are not configured."}
                if not enabled:
                    return name, result
                result["lastCheckedAt"] = utc_now()
                try:
                    async with httpx.AsyncClient(timeout=5, follow_redirects=False) as client:
                        response = await client.get(service_url(env, path), headers=gpu_headers())
                        response.raise_for_status()
                        data = response.json()
                    if name == "cosmos":
                        models = [m["id"] for m in data.get("data", []) if isinstance(m.get("id"), str)]
                        if not models:
                            raise ValueError("No model is available")
                        result["model"] = next((m for m in models if m == os.getenv("COSMOS3_REASON_MODEL")), models[0])
                    elif data.get("ok") is not True or data.get("model_loaded") is not True:
                        raise ValueError("Detector is not ready")
                    else:
                        result["model"] = Path(str(data.get("model") or "YOLO")).name
                    result.update(status="connected", lastSuccessAt=result["lastCheckedAt"], detail="Authenticated service health check succeeded; this check does not run video inference.")
                except Exception as exc:
                    result["detail"] = public_error(exc)
                return name, result
            pairs = await asyncio.gather(probe("cosmos", "COSMOS3_REASON_URL", "/v1/models"), probe("yolo", "YOLO_URL", "/healthz"))
            _gpu_health, _gpu_health_at, _gpu_health_key = dict(pairs), time.monotonic(), key
    return {name: {**result, "lastInferenceAt": service_events.get(name, {}).get("lastSuccessAt"),
                   "lastOperationStatus": ("connected" if service_events[name]["success"] else "unavailable") if name in service_events else "unverified",
                   "lastOperationDetail": service_events.get(name, {}).get("detail")}
            for name, result in _gpu_health.items()}


class PublicCache:
    """Only public-source payloads are cached on disk; provider credentials never are."""
    def __init__(self, directory: Path):
        self.directory = directory
        self.locks: dict[str, asyncio.Lock] = {}

    async def get(self, key: str, ttl: int, loader):
        async with self.locks.setdefault(key, asyncio.Lock()):
            path = self.directory / f"{key}.json"
            previous = None
            try:
                previous = json.loads(path.read_text())
                if time.time() - previous["cachedAt"] < ttl:
                    return previous["payload"], {"mode": "connected", "fetchedAt": previous["fetchedAt"], "cached": True}
            except (OSError, ValueError, KeyError, TypeError):
                previous = None
            try:
                payload = await loader()
                fetched = utc_now()
                self.directory.mkdir(parents=True, exist_ok=True)
                temporary = path.with_suffix(".tmp")
                temporary.write_text(json.dumps({"cachedAt": time.time(), "fetchedAt": fetched, "payload": payload}))
                temporary.replace(path)
                return payload, {"mode": "connected", "fetchedAt": fetched, "cached": False}
            except Exception as exc:
                error = public_error(exc)
                if previous:
                    return previous["payload"], {"mode": "stale", "fetchedAt": previous["fetchedAt"], "cached": True, "error": error}
                return None, {"mode": "unavailable", "fetchedAt": None, "cached": False, "error": error}


