class FrontendFiles(StaticFiles):
    async def get_response(self, path: str, scope: dict):
        is_html = path in {"", ".", "index.html"} or path.lower().endswith(".html")
        if is_html:
            # Reproducible bundles have normalized mtimes. Starlette's size/mtime
            # ETags can therefore collide when two index files have equal length.
            # Always fetch HTML content, even from clients holding an old ETag.
            scope = {**scope, "headers": [(key, value) for key, value in scope.get("headers", []) if key.lower() not in {b"if-none-match", b"if-modified-since"}]}
        response = await super().get_response(path, scope)
        if is_html or response.headers.get("content-type", "").startswith("text/html"):
            response.headers["Cache-Control"] = "no-store, max-age=0"
            response.headers["Pragma"] = "no-cache"
            response.headers["Expires"] = "0"
            for header in ("etag", "last-modified"):
                if header in response.headers:
                    del response.headers[header]
        return response

    async def check_config(self):
        # Development may start the API before the initial Vite build exists.
        if not (ROOT / "dist").is_dir():
            raise HTTPException(404, "Frontend build not found. Run Vite or build dist/.")
        await super().check_config()


