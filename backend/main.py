class VSSClient:
    def __init__(self):
        self.token = None
        self.lock = asyncio.Lock()

    @property
    def settings(self):
        return (os.getenv("VSS_URL") or os.getenv("INGRESS_URL") or "", os.getenv("VSS_USERNAME") or os.getenv("TEAM_USERNAME") or "", os.getenv("VSS_PASSWORD") or "")

    @property
    def configured(self):
        return all(self.settings)

    async def login(self, client: httpx.AsyncClient, force=False):
        async with self.lock:
            if self.token and not force:
                return self.token
            base, username, password = self.settings
            if not all((base, username, password)):
                raise RuntimeError("VSS not configured")
            response = await client.post(base.rstrip("/") + "/api/v1/auth/login", json={"username": username, "password": password})
            response.raise_for_status()
            self.token = response.json()["access_token"]
            return self.token

    async def request(self, path: str, body: dict):
        async with httpx.AsyncClient(timeout=90, follow_redirects=False) as client:
            token = await self.login(client)
            response = await client.post(self.settings[0].rstrip("/") + path, json=body, headers={"Authorization": f"Bearer {token}"})
            if response.status_code == 401:
                token = await self.login(client, force=True)
                response = await client.post(self.settings[0].rstrip("/") + path, json=body, headers={"Authorization": f"Bearer {token}"})
            response.raise_for_status()
            return response.json()


